def test_spurious_rate(influence_graph_with_map):
    """
    Spurious rate: fraction of returned influenced decisions not in the gold set,
    averaged over all 50 queries.

    Threshold: <= 0.10  (Semantica production SLA).
    A high spurious rate means compliance changes incorrectly propagate to
    unrelated decisions.

    Tracks 1.3 and 30 share this function.
    """
    graph, id_map, fixture = influence_graph_with_map
    queries = fixture["queries"]

    spurious_rates: List[float] = []
    for q in queries:
        query_uuid = id_map.get(q["query_logical_id"])
        # Use depth-5 gold as the broadest set for spurious-rate evaluation
        gold_uuids = {id_map[lid] for lid in q["depth_5_influenced_logical_ids"] if lid in id_map}

        if not query_uuid:
            continue

        try:
            result = graph.analyze_decision_influence(query_uuid, max_depth=5)
        except ValueError:
            spurious_rates.append(0.0)
            continue

        found = _influenced_ids_from_result(result)
        spurious_rates.append(_spurious_rate(found, gold_uuids))

    assert spurious_rates, "No valid queries in influence ground-truth fixture"
    avg_spurious = sum(spurious_rates) / len(spurious_rates)

    assert avg_spurious <= THRESHOLD_SPURIOUS_RATE, (
        f"Spurious rate {avg_spurious:.4f} > {THRESHOLD_SPURIOUS_RATE}. "
        f"analyze_decision_influence() returns too many false-positive influenced decisions. "
        f"Silent false positives cause incorrect policy rollbacks."
    )


def test_influence_entry_points_fixture(influence_graph_with_map):
    """
    Exercise the real influence-analysis entry points on the shared fixture.

    Track 1.3 is fixture-backed by design; this test ensures the benchmark
    covers both analysis and causality-tracing modules named in subissue #571.
    """
    from semantica.context.agent_context import AgentContext

    graph, id_map, fixture = influence_graph_with_map
    agent = AgentContext(
        vector_store=_NullVectorStore(),
        knowledge_graph=graph,
        decision_tracking=True,
        advanced_analytics=False,
        kg_algorithms=False,
        vector_store_features=False,
    )

    checked = 0
    for query in fixture["queries"][:10]:
        query_uuid = id_map.get(query["query_logical_id"])
        if not query_uuid:
            continue

        graph_result = graph.analyze_decision_influence(query_uuid, max_depth=5)
        agent_result = agent.analyze_decision_influence(query_uuid, max_depth=5)
        graph_ids = _influenced_ids_from_result(graph_result)
        agent_ids = _influenced_ids_from_result(agent_result)

        assert graph_ids, "ContextGraph.analyze_decision_influence() returned no influenced decisions"
        assert agent_ids == graph_ids, (
            "AgentContext.analyze_decision_influence() diverged from the underlying "
            "ContextGraph result on the shared influence benchmark fixture."
        )

        causality_report = graph.trace_decision_causality(query_uuid, max_depth=5)
        assert isinstance(causality_report, list), "trace_decision_causality() must return a causal report list"
        checked += 1

    assert checked > 0, "No influence queries were evaluated for API coverage"
