def test_influence_recall_at_3(influence_graph_with_map):
    """
    Influence recall@3: fraction of gold downstream decisions found by
    analyze_decision_influence(max_depth=3) averaged over all 50 queries.

    Threshold: >= 0.85  (internal ground-truth fixture SLA).

    Tracks 1.3 and 30 share this function.
    """
    graph, id_map, fixture = influence_graph_with_map
    queries = fixture["queries"]

    recalls: List[float] = []
    for q in queries:
        query_uuid = id_map.get(q["query_logical_id"])
        gold_uuids = {id_map[lid] for lid in q["depth_3_influenced_logical_ids"] if lid in id_map}

        if not query_uuid or not gold_uuids:
            continue

        try:
            result = graph.analyze_decision_influence(query_uuid, max_depth=3)
        except ValueError:
            recalls.append(0.0)
            continue

        found = _influenced_ids_from_result(result)
        recalls.append(_recall(found, gold_uuids))

    assert recalls, "No valid queries found in influence ground-truth fixture"
    avg_recall = sum(recalls) / len(recalls)

    assert avg_recall >= THRESHOLD_INFLUENCE_RECALL_3, (
        f"Influence recall@3 = {avg_recall:.4f} < {THRESHOLD_INFLUENCE_RECALL_3}. "
        f"analyze_decision_influence(max_depth=3) misses too many downstream decisions. "
        f"({len([r for r in recalls if r < 1.0])} / {len(recalls)} queries had missed decisions)"
    )


